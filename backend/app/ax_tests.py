def career_score(picks: list[int]) -> dict:
    """picks: 문항 순서대로 고른 보기 번호(0~3). → {code, second, pct{유형: 0~100}}

    유형마다 보기에 나온 횟수가 달라(6~7번) 나온 횟수 대비 고른 비율로 비교한다. 같으면 마지막에 고른 쪽, 그다음 기본 순서."""
    seen = {k: 0 for k in CAREER_ORDER}
    got = {k: 0 for k in CAREER_ORDER}
    last: dict[str, int] = {}
    for qi, ((_, opts), p) in enumerate(zip(CAREER_QUESTIONS, picks)):
        for _, code in opts:
            seen[code] += 1
        code = opts[p][1]
        got[code] += 1
        last[code] = qi
    pct = {k: round(got[k] / seen[k] * 100) for k in CAREER_ORDER}
    ranked = sorted(CAREER_ORDER, key=lambda k: (-got[k] / seen[k], -last.get(k, -1), CAREER_ORDER.index(k)))
    return {"code": ranked[0], "second": ranked[1], "pct": pct}
